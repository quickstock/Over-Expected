"""Generate references.bib from citations_verified.json.

The .bib is never hand-edited. Every field comes from the API record that
verified the citation, so the bibliography cannot drift from what was checked.
Re-run verify_citations.py then this, in that order.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).parent

SMALL = {"a", "an", "and", "as", "at", "but", "by", "for", "from", "in", "is",
         "of", "on", "or", "the", "to", "vs", "with"}


def _titlecase(s: str) -> str:
    """Sentence-ish title case for the ALL-CAPS records CrossRef holds for
    pre-war journals. Acronyms of 2-4 chars are left alone."""
    words = s.split()
    out = []
    for i, w in enumerate(words):
        core = w.strip(".,:;()")
        if i > 0 and core.lower() in SMALL:
            out.append(w.lower())
        else:
            out.append(w.capitalize())
    return " ".join(out)


SMART = {"’": "'", "‘": "'", "“": '"', "”": '"',
         "–": "--", "—": "---", "−": "-", " ": " "}


def deunicode(s: str) -> str:
    """T1/EC fonts have no glyph for curly quotes. Normalise to ASCII."""
    for a, b in SMART.items():
        s = s.replace(a, b)
    return s


def fix_title(t: str) -> str:
    t = deunicode(t)
    t = re.sub(r"<[^>]+>", "", t)                    # strip HTML/MathML tags
    t = re.sub(r"\s*\d+\s*$", "", t)                 # trailing footnote marker
    t = re.sub(r"\s+", " ", t).strip()
    letters = [c for c in t if c.isalpha()]
    if letters and sum(c.isupper() for c in letters) / len(letters) > 0.8:
        t = _titlecase(t)
    return t                                          # braced as a whole below


def _fix_caps_name(n: str) -> str:
    """"BRIER, GLENN W." -> "Brier, Glenn W." Leave normal names untouched."""
    letters = [c for c in n if c.isalpha()]
    if not letters or sum(c.isupper() for c in letters) / len(letters) < 0.8:
        return n
    parts = []
    for tok in n.split():
        core = tok.strip(".,")
        if len(core) == 1:
            parts.append(tok)                         # initials: W.
        else:
            parts.append(tok.capitalize())
    return " ".join(parts)


def fmt_authors(authors: list[str], source: str) -> str:
    if not authors:
        return ""
    if source == "crossref":
        # already "Family, Given"
        return " and ".join(
            deunicode(_fix_caps_name(a)) for a in authors if a.strip(" ,")
        )
    # OpenAlex gives "Given Family"; flip to "Family, Given"
    out = []
    for a in authors:
        parts = a.split()
        if len(parts) >= 2:
            out.append(f"{parts[-1]}, {' '.join(parts[:-1])}")
        else:
            out.append(a)
    return " and ".join(out)


# Some indexes return the *repository* that holds a record rather than the venue
# that published it: OpenAlex gives "HAL" for the NeurIPS LightGBM paper, "Lirias"
# for the KDD soccer paper, "arXiv (Cornell University)" for two others. The DOI,
# authors and title still come from the API; only the human-readable venue is
# corrected here, with the correction recorded so a reviewer can check it.
VENUE_OVERRIDE = {
    "ke2017lightgbm": {
        "container": "Advances in Neural Information Processing Systems 30 "
                     "(NeurIPS 2017)",
        "publisher": None, "type": "proceedings-article"},
    "miller2014factorized": {
        "container": "Proceedings of the 31st International Conference on "
                     "Machine Learning (ICML 2014)",
        "publisher": None, "type": "proceedings-article"},
    "guo2017calibration": {
        "container": "Proceedings of the 34th International Conference on "
                     "Machine Learning (ICML 2017)",
        "publisher": None, "type": "proceedings-article"},
}

TYPE_MAP = {
    "journal-article": "article",
    "proceedings-article": "inproceedings",
    "book-chapter": "incollection",
    "posted-content": "misc",
    "article": "article",
}


def main() -> None:
    recs = json.loads((HERE / "citations_verified.json").read_text())
    lines, no_doi = [], []
    lines.append("% Generated by paper/make_bib.py from "
                 "paper/citations_verified.json. Do not edit by hand.\n")
    lines.append(f"% {len(recs)} entries, every one resolved against "
                 "CrossRef or OpenAlex.\n\n")

    overridden = []
    for r in sorted(recs, key=lambda x: x["key"]):
        if r["key"] in VENUE_OVERRIDE:
            r = {**r, **{k: v for k, v in VENUE_OVERRIDE[r["key"]].items()}}
            overridden.append(r["key"])
        etype = TYPE_MAP.get((r.get("type") or "").lower(), "article")
        if not r.get("hasDoi", bool(r.get("doi"))):
            no_doi.append(r["key"])
            etype = "inproceedings"
        f = [f"  author       = {{{fmt_authors(r['authors'], r['source'])}}}",
             f"  title        = {{{{{fix_title(r['title'])}}}}}"]
        if r.get("year"):
            f.append(f"  year         = {{{r['year']}}}")
        if r.get("container"):
            key = "booktitle" if etype == "inproceedings" else "journal"
            f.append(f"  {key:<12} = {{{deunicode(r['container'])}}}")
        for name, val in (("volume", r.get("volume")),
                          ("number", r.get("issue")),
                          ("pages", r.get("page")),
                          ("publisher", r.get("publisher"))):
            if val:
                f.append(f"  {name:<12} = {{{val}}}")
        if r.get("doi"):
            f.append(f"  doi          = {{{r['doi']}}}")
        lines.append(f"@{etype}{{{r['key']},\n" + ",\n".join(f) + "\n}\n\n")

    (HERE / "references.bib").write_text("".join(lines))
    print(f"wrote references.bib — {len(recs)} entries")
    if no_doi:
        print(f"  {len(no_doi)} without a DOI (verified via OpenAlex "
              f"metadata instead): {', '.join(no_doi)}")
    if overridden:
        print(f"  {len(overridden)} venue corrections applied (index returned "
              f"a repository, not the publisher): {', '.join(overridden)}")


if __name__ == "__main__":
    main()
